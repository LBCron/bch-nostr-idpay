/**
 * Extracts the connected user's BCH P2PKH & CashTokens (`bitcoincash:z...`) identity
 * directly from an active WizardConnect `DappConnectionManager` BIP32 xpub session
 * with zero extra network round-trips!
 */
export function deriveBchIdentityFromWizardManager(
  manager: DappConnectionManager,
  network: BchNetworkId = 'mainnet',
  addressIndex = 0n,
): BchKeyIdentity | null {
  // Child index 0 = Receive (m/44'/145'/0'/0)
  const pubkey = manager.getPubkey(0, addressIndex);
  if (!pubkey || pubkey.length !== 33) {
    return null;
  }
  return deriveBchIdentityFromPublicKey(pubkey, network);
}

/**
 * Encodes a CashScript `WcTransactionObject` into WizardConnect relay-safe extended JSON
 * (`<Uint8Array: 0x...>` and `<bigint: Xn>`) per `@wizardconnect/core/serialize`.
 */
export function serializeWcTransactionForRelay(
  wcTransaction: WcTransactionObject,
): SignTransactionRequest['transaction'] {
  return JSON.parse(stringify(wcTransaction)) as SignTransactionRequest['transaction'];
}

/**
 * Sends a `WcTransactionObject` (generated by CashScript `TransactionBuilder.generateWcTransactionObject`)
 * over an active WizardConnect NIP-59 gift-wrapped session and returns the signed raw BCH tx hex.
 */
export async function requestWizardConnectSignature(params: {
  manager: DappConnectionManager;
  wcTransaction: WcTransactionObject;
  inputPaths?: [number, PathName, number][];
  signal?: AbortSignal;
}): Promise<SignTransactionResponse> {
  const inputPaths: [number, PathName, number][] =
    params.inputPaths ??
    params.wcTransaction.transaction.inputs.map((_, idx) => [idx, PATH_RECEIVE, 0]);

  const relaySafeTransaction = serializeWcTransactionForRelay(params.wcTransaction);

  return params.manager.signTransaction(
    {
      transaction: relaySafeTransaction,
      inputPaths,
    },
    params.signal ? { signal: params.signal } : undefined,
  );
}

/**
 * Helper to create a standalone programmatic WizardConnect dApp session (used in Node/Vitest E2E
 * and headless scripts).
 */
export function createProgrammaticWizardDapp(options: {
  dappName?: string;
  dappIcon?: string;
  relayUrls?: string[];
}) {
  const manager = new DappConnectionManager(
    options.dappName ?? 'CashLink DID',
    options.dappIcon ?? 'https://bchblaze.cash/favicon.ico',
    { session: false },
  );
  const relay = initiateDappRelay(
    (payload) => {
      manager.updateConnection(payload.client, payload.status);
    },
    {
      explicitRelayUrls: options.relayUrls ?? WIZARDCONNECT_RELAY_URLS,
    },
  );
  manager.attachRelay(relay);
  return { manager, relay };
}

/**
 * Full BIP32/BIP44 (`m/44'/145'/0'`) non-custodial Bitcoin Cash `WalletAdapter` implementing
 * `@wizardconnect/wallet`'s real `hdwalletv1` protocol (`getXpub`, `getPublicKey`, `signTransaction`).
 */
export class NonCustodialBip32WizardWalletAdapter implements WalletAdapter {
  public readonly walletName: string;
  public readonly walletIcon: string;
  private readonly seed: Uint8Array;
  private readonly network: BchNetworkId;

  constructor(options: {
    seed: Uint8Array;
    network?: BchNetworkId;
    walletName?: string;
    walletIcon?: string;
  }) {
    if (options.seed.length < 16 || options.seed.length > 64) {
      throw new Error('BIP32 seed must be between 16 and 64 bytes');
    }
    this.seed = options.seed;
    this.network = options.network ?? 'mainnet';
    this.walletName = options.walletName ?? 'CashLink Non-Custodial HD Wallet';
    this.walletIcon = options.walletIcon ?? 'https://bchblaze.cash/favicon.ico';
  }

  getRelayPrivateKey(uri: string): Uint8Array {
    const preimage = new Uint8Array(this.seed.length + uri.length);
    preimage.set(this.seed, 0);
    preimage.set(utf8ToBin(uri), this.seed.length);
    return sha256.hash(preimage);
  }

  private getBranchPrivateNode(path: DerivationPath) {
    const master = deriveHdPrivateNodeFromSeed(this.seed, { assumeValidity: true, throwErrors: true });
    const branchIndex = Number(path);
    const derived = deriveHdPath(master, `m/44'/145'/0'/${branchIndex}`);
    if (typeof derived === 'string') {
      throw new Error(`HD derivation failed for path ${branchIndex}: ${derived}`);
    }
    return derived;
  }

  deriveChildPrivateKey(path: DerivationPath, index: bigint): Uint8Array {
    const branch = this.getBranchPrivateNode(path);
    const child = deriveHdPrivateNodeChild(branch, Number(index));
    if (typeof child === 'string') {
      throw new Error(`Child HD derivation failed: ${child}`);
    }
    return child.privateKey;
  }

  getPublicKey(path: DerivationPath, index: bigint): Uint8Array {
    const privKey = this.deriveChildPrivateKey(path, index);
    const pub = secp256k1.derivePublicKeyCompressed(privKey);
    if (typeof pub === 'string') {
      throw new Error(`Public key derivation failed: ${pub}`);
    }
    return pub;
  }

  getXpub(path: DerivationPath): string {
    const branchPriv = this.getBranchPrivateNode(path);
    const branchPub = deriveHdPublicNode(branchPriv);
    return encodeHdPublicKey({
      network: this.network === 'mainnet' ? 'mainnet' : 'testnet',
      node: branchPub,
    }).hdPublicKey;
  }

  async signTransaction(request: SignTransactionRequest): Promise<SignTransactionResult> {
    const rawReq = request.transaction as unknown as {
      transaction: {
        version: number;
        locktime: number;
        inputs: Array<{
          outpointIndex: number;
          outpointTransactionHash: Uint8Array | string;
          sequenceNumber: number;
          unlockingBytecode: Uint8Array | string;
        }>;
        outputs: Array<{
          lockingBytecode: Uint8Array | string;
          valueSatoshis: bigint | number | string;
          token?: {
            amount: bigint | number | string;
            category: Uint8Array | string;
            nft?: {
              capability: 'none' | 'mutable' | 'minting';
              commitment: Uint8Array | string;
            };
          };
        }>;
      };
      sourceOutputs: Array<{
        lockingBytecode: Uint8Array | string;
        valueSatoshis: bigint | number | string;
        token?: {
          amount: bigint | number | string;
          category: Uint8Array | string;
          nft?: {
            capability: 'none' | 'mutable' | 'minting';
            commitment: Uint8Array | string;
          };
        };
      }>;
    };

    const tx = {
      version: Number(rawReq.transaction.version),
      locktime: Number(rawReq.transaction.locktime),
      inputs: rawReq.transaction.inputs.map((inp) => ({
        outpointIndex: Number(inp.outpointIndex),
        outpointTransactionHash: toUint8Array(inp.outpointTransactionHash),
        sequenceNumber: Number(inp.sequenceNumber),
        unlockingBytecode: toUint8Array(inp.unlockingBytecode),
      })),
      outputs: rawReq.transaction.outputs.map((out) => ({
        lockingBytecode: toUint8Array(out.lockingBytecode),
        valueSatoshis: toBigInt(out.valueSatoshis),
        ...(out.token
          ? {
              token: {
                amount: toBigInt(out.token.amount),
                category: toUint8Array(out.token.category),
                ...(out.token.nft
                  ? {
                      nft: {
                        capability: out.token.nft.capability,
                        commitment: toUint8Array(out.token.nft.commitment),
                      },
                    }
                  : {}),
              },
            }
          : {}),
      })),
    };

    const sourceOutputs = rawReq.sourceOutputs.map((so) => ({
      lockingBytecode: toUint8Array(so.lockingBytecode),
      valueSatoshis: toBigInt(so.valueSatoshis),
      ...(so.token
        ? {
            token: {
              amount: toBigInt(so.token.amount),
              category: toUint8Array(so.token.category),
              ...(so.token.nft
                ? {
                    nft: {
                      capability: so.token.nft.capability,
                      commitment: toUint8Array(so.token.nft.commitment),
                    },
                  }
                : {}),
            },
          }
        : {}),
    }));

    for (const [inputIndex, pathName, childAddressIndex] of request.inputPaths) {
      const derivPath =
        pathName === 'change'
          ? DerivationPath.Change
          : pathName === 'defi'
            ? DerivationPath.Cauldron
            : DerivationPath.Receive;
      const privKey = this.deriveChildPrivateKey(derivPath, BigInt(childAddressIndex));
      const sigTemplate = new SignatureTemplate(privKey);
      const unlocker = sigTemplate.unlockP2PKH();
      tx.inputs[inputIndex].unlockingBytecode = unlocker.generateUnlockingBytecode({
        transaction: tx,
        sourceOutputs,
        inputIndex,
      });
    }

    const encoded = encodeTransactionBCH(tx);
    return {
      signedTransaction: binToHex(encoded),
    };
  }
}

export { WalletConnectionManager, DappConnectionManager, DerivationPath };
